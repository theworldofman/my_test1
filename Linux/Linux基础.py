# 计算机是由硬件和软件组成的,操作系统是硬件和用户之间的桥梁
# 操作系统:，操作系统（Operating System, OS） 是管理计算机硬件与软件资源的系统软件，它是用户与计算机硬件之间的接口。主要职责包括：
# 进程管理 — 调度和管理正在运行的程序
# 内存管理 — 分配和回收内存空间
# 文件系统管理 — 组织、存储和检索数据
# 设备管理 — 驱动和控制硬件设备（键盘、显示器、磁盘等）
# 用户接口 — 提供命令行（CLI）或图形界面（GUI）供用户操作
# 常见的操作系统有：Linux、Windows、macOS 等。

# Linux:是由Linux系统内核和系统级应用程序
# 内核提供系统最核心的功能:如调度cpu,内存,文件系统,IO等
# 系统级应用程序,可以理解为出厂自带程序,可供用户快速上手操作系统如文件管理器,图片查看等

# 虚拟机通过软件模拟出一个完整的计算机系统，包括CPU、内存、硬盘、网卡等硬件设备，运行在物理机（宿主机）之上，能够像独立计算机一样安装和运行自己的操作系统及应用程序。

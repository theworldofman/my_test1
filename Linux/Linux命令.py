# 通过ls-l展开可以查看文件权限信息
# 在第一部分可以查看文件类型和权限信息
# 开头是d,l,-表示类型,d表示文件夹,l表示软链接,-表示普通文件
# 后面9位三三一组,分别表示用户权限,用户组权限,其他用户权限
# 每组3位,分别表示读权限(r -),写权限(w -),执行权限(x -)

# 第三第四部分可以查看文件的所属用户和用户组

# chmod修改文件权限
# chmod [-R] 权限 文件或文件夹
# -R,对文件夹内的全部内容应用同样的操作
# 权限细节:u=用户权限(前三),g=用户组权限(中三),o=其他用户权限(后三),a=所有用户权限
# 例子:chmod u=rwx,g=w,o=r 文件名

# 权限可以用三位数字表示,每一位分别表示读权限(4),写权限(2),执行权限(1)
# 例子:chmod 755 文件名
# 755表示所有用户都有读权限,用户组用户有写权限,其他用户没有权限
# 就是二进制表示权限
# 只有所属用户和root才可以修改文件权限

# 只能由root用户修改文件所有者
# chown [-R] [用户][:][用户组] 文件或文件夹
# -R通chmod
# 用户:表示修改用户,不填则不修改用户
# 用户组:表示修改用户组,不填则不修改用户组
# :表示分隔符,区别用户和用户组


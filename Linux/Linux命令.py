# Linux命令的基础格式
# command [-options] [parameter]
# command:就是命令本身
# -options:[可选,非必填]就是命令的选项,用于修改命令的默认行为
# parameter:[可选,非必填]就是命令的参数,用于指定命令操作的对象

# ls 命令 列出当前工作目录(默认HOME目录)下的内容
# ls [-a -l -h] [Linux路径]
# 注意HOME不是home,HOME的Linux路径是:/home/用户名
# -a:显示所有文件,包括隐藏文件(以.开头)
# -l:以列表显示文件信息,并有更多信息
# -h:以人类可读的格式显示文件大小,和l一起使用不然没啥作用
# 当然我们可以混合使用这些选项,例如:ls -a -l -h
# 参数:Linux路径 默认为当前工作目录,可以填入其他目录路径列出该目录下的内容


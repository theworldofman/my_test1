# **HTTP（HyperText Transfer Protocol，超文本传输协议）**，是一套**规则**，规定两台电脑之间怎么互相传递文本、数据。
# 你调用大模型，本质就是**客户端（你的 Python 程序）通过 HTTPS（HTTP + 加密）发送 API 请求给远端服务器，服务器处理后，再通过 HTTPS 返回结果给你**。

# URL:用来定位互联网上资源的地址，也就是我们常说的网页地址、网址。
# URL 是给人看的文字地址；IP 地址是计算机识别的数字地址。DNS 负责把域名（URL 里的主机部分）翻译成 IP 地址。
# **HTTPS 是什么**
# HTTPS = HTTP + TLS 加密。
# 它规定**客户端（浏览器 / 你的程序）和服务器之间怎么可靠、加密地传递报文**。
# 真正来回传输的是 **HTTP 报文（请求报文、响应报文）**，报文的**body 部分**可以放 JSON、HTML、文本、图片二进制等等。

 # 请求头（Request Headers）一句话概括
# **请求头是放在 HTTP 请求报文里，附加在请求体前面的一堆「键：值」信息，用来告诉服务器：这次请求的各种附加规则、客户端身份、数据格式、权限凭证等。**

# - 裸写：用 `requests`，自己拼 URL、写 headers、构造 JSON、处理状态码、捕获网络报错、解析返回 JSON。
# - SDK：大模型厂商写好的 Python 库（比如 `openai`、`doubao`、`deepseek`），**底层内部还是用 HTTP 请求**，只是把所有 HTTP 细节全部藏起来了。


# **URL 就是互联网资源的完整地址**，用来告诉程序 / 浏览器：服务器在哪、要访问哪个接口 / 网页。

# get和post请求区别
# 约定：GET = 获取查询数据（只读，不改动服务器）；          POST = 提交数据（会让服务器产生动作）
# 设计目的:GET获取 / 查询数据，不修改服务器状态              POST:提交数据，触发服务器运算、新增内容AI 对话、登录、上传）
# 数据存放位置:GET:数据放在URL 地址后面（query 查询参数）    POST:数据放在请求体 Body（就是 Postman 的 Body 面板，放 JSON 的地方）

# 发送HTML请求时
#
# Params	告诉服务器“我要什么数据”（筛选、条件）	拼在 URL 里，跟在 ? 后面
# Headers	告诉服务器“我是谁”（身份、格式要求）	隐藏在请求头里，不显示在 URL 上
# Body	发给服务器的具体数据（通常用于提交表单、修改数据）	GET 请求通常没有，POST 请求才有





# 数据分组
# df.groupby('列名'),按某一列的值进行分组,可以单独保存这个分组对象，后面随时拿它做各种操作；但只写 groupby，不接任何方法，打印出来就只是对象地址，看不到数据
# df.groupby(['列1', '列2'])
# 分组后可以进行各种统计操作，例如：count(), sum(), mean(), max(), min(), std()等
# count() 统计个数
# sum() 求和
# mean() 平均值
# max() 最大值
# min() 最小值
# std() 标准差
# agg() 自定义统计操作
# 例如：df.groupby('列名').agg('sum', 'mean')
# 也可以传入一个字典，指定对每一列进行不同的统计操作
# 例如：df.groupby('列名').agg({'列1': 'sum', '列2': 'mean'})
# 还可以使用lambda函数进行自定义统计操作，例如：df.groupby('列名').agg(lambda x: x.sum())
















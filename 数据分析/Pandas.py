# 缺失值处理
# df.dropna():删除缺失值,注意是直接删除这一行,当然也可以设置为删除列,例如：df.dropna(axis=1)
# df.fillna():填充缺失值,例如：df.fillna(0)
# df.ffill():前向填充缺失值,用上一行的数据填充
# df.bfill():后向填充缺失值,用下一行的数据填充

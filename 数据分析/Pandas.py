# 删除
# df.drop_duplicates():删除重复值,注意是直接删除这一行,当然也可以设置为删除列,例如：df.drop_duplicates(axis=1)
# 正常情况下是保留第一次,删除第二次及以后的重复值,可以用keep参数设置保留哪个,例如：df.drop_duplicates(keep='last')保留最后一个删除其他,keep=false全删

# 虚拟机（Virtual Machine，VM）：是一套软件模 完整计算机系统，它运行在你真实的物理电脑之上，拥有独立的 CPU、内存、硬盘、网卡，和真实电脑几乎一样，可以单独安装操作系统、软件。
#  简单一句话:一台物理电脑里，用软件 “变出” 另一台独立的电脑

# **终端就是一个文字界面，用来输入命令，直接指挥操作系统**，也叫命 令行。


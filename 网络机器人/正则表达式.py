# 正则表达式-语法

# 1.元字符:有特殊含义的字符
# 普通字符-字母,数字,汉字及大多数字符,直接匹配自身
# .:匹配任意单个字符（除换行符 \n，加 re.S 后可含换行）
# \d:匹配一个数字 0-9
# \D:匹配一个非数字
# \w :匹配一个单词字符（字母、数字、下划线、汉字）
# \W:匹配一个非单词字符
# \s:匹配一个空白字符（空格、制表符、换行）
# \S :匹配一个非空白字符
# \:转义符（把特殊字符变普通字符，如 \. 匹配真正的点）

# 2.字符类 [...]
# [abc]:匹配方括号内的任意一个字符
# [a-z]:匹配a到z之间的任意一个字符
# [a-z0-9]:匹配a到z或0到9之间的任意一个字符
# [^abc]:匹配除了abc之外的任意一个字符

# 3.量词
# +:匹配前面的元素一次或多次
# *:匹配前面的元素零次或多次
# ?:匹配前面的元素零次或一次
# {n}:匹配前面的元素恰好 n 次
# {n,}:匹配前面的元素至少 n 次
# {n,m}:匹配前面的元素至少 n 次，但不超过 m 次

# 4.锚点
# ^:匹配字符串的开始
# $:匹配字符串的结束

# 5.分组与引用 (...)
# ( ):分组,一个括号里为一组
# | 或的意思,匹配左右任意一个表达式

